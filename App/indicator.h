#ifndef INDICATOR_H
#define INDICATOR_H

#include "app_env.h"

/* ================================================================
 * 执行器层
 *
 * 把"环境状态 + 配置"变成实际的输出动作，目前两路：
 *
 * ---- 风扇（见 docs/工业环境检测系统-硬件台账.xlsx）----
 *
 *   PA8 = TIM1_CH1  →  TB6612 的 PWMA        转速 / 开关
 *
 *   其余都在硬件上接死了，软件碰不到：
 *     AIN1 直接接 3.3V、AIN2 直接接 GND   → 方向固定为"正转"
 *     STBY 直接接 3.3V                    → 驱动常使能
 *
 *   所以**只需要 PA8 一根控制线**。副作用是方向脚不可能出现
 *   "两个同时为高"（TB6612 那会变成短路制动），少一类出错的可能。
 *
 * ---- 白灯 ----
 *
 *   PB6 = TIM4_CH1  →  白灯（LED 灯珠，PWM 调光）
 *
 *   按"暗到什么程度"连续调光：够亮时灭，越暗越亮。
 *   阈值由 cfg.light_lo 给（上位机和界面都能改）。
 *
 * 两路都挂在同一个 Task_Output 上，共用一次 env/cfg 快照。
 * ================================================================ */

/* 启动 PWM 输出。由 Task_Output 进循环前调一次。 */
void indicator_init(void);

/* 按当前环境数据和配置更新所有输出。
   不读共享数据、不碰 LVGL —— 传入什么就算什么，方便单独推理。 */
void indicator_update(const env_t *e, const cfg_t *c);

#endif /* INDICATOR_H */

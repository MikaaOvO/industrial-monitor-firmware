#ifndef INDICATOR_H
#define INDICATOR_H

#include "app_env.h"

/* ================================================================
 * 执行器层
 *
 * 把"环境状态 + 配置"变成实际的输出动作。目前只有风扇。
 *
 * ---- 风扇硬件（见 docs/工业环境检测系统-硬件台账.xlsx）----
 *
 *   PA8 = TIM1_CH1  →  TB6612 的 PWMA        转速 / 开关
 *
 *   其余都在硬件上接死了，软件碰不到：
 *     AIN1 直接接 3.3V、AIN2 直接接 GND   → 方向固定为"正转"
 *     STBY 直接接 3.3V                    → 驱动常使能
 *
 *   所以**只需要 PA8 一根控制线**。副作用是方向脚不可能出现
 *   "两个同时为高"（TB6612 那会变成短路制动），少一类出错的可能。
 *
 * 以后要加灯光（PB6 / TIM4_CH1，读 light_idx 和 light_lo）也放这里，
 * 和风扇同一个任务驱动。
 * ================================================================ */

/* 启动 PWM 输出。由 Task_Output 进循环前调一次。 */
void indicator_init(void);

/* 按当前环境数据和配置更新所有输出。
   不读共享数据、不碰 LVGL —— 传入什么就算什么，方便单独推理。 */
void indicator_update(const env_t *e, const cfg_t *c);

#endif /* INDICATOR_H */

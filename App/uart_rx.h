#ifndef UART_RX_H
#define UART_RX_H

#include <stdbool.h>

/* ================================================================
 * 串口接收的"机制层"
 *
 * 这一层只干两件事：从串口把字节捞出来、重新武装接收中断，然后把字节
 * 交给对应的协议层。协议层（voc.c / host_proto.c）不碰 HAL 的接收链路，
 * 只负责"一堆字节怎么组成一帧"。
 *
 * 两个串口共用这一个 HAL_UART_RxCpltCallback，里面按 Instance 分发。
 * 各模块自己的那个回调就删掉了 —— 一个工程只能有一个
 * HAL_UART_RxCpltCallback 定义（HAL 里是 __weak，重定义会链接冲突）。
 *
 * ---- 为什么两个串口都用"单字节中断" ----
 *
 *   轮询：      115200 下一个字节只有 87µs，20ms 轮询一次中间会到 200 多个
 *               字节，只能捞到 1 个，一帧都收不全。9600 也不行（1.04ms/字节，
 *               20ms 轮询漏 19 个）。
 *   DMA+空闲：  对固定长度的小帧是杀鸡用牛刀，还多一层配置和缓冲。
 *   单字节中断：不丢字节，每个串口只要在 CubeMX 里勾一个 NVIC 复选框。
 *
 * ---- 中断里不调 FreeRTOS 的 API ----
 *
 * ISR 只写静态缓冲区、重新武装接收，不调任何 xxxFromISR()。所以即使有人
 * 把 NVIC 优先级设到 5 以下，也不会触发 configASSERT 卡死，最多是收不到
 * 数据 —— 把"静默的优先级错误"换成了"可观察的功能异常"。
 * ================================================================ */

/* 启动 UART4（21VOC）的接收中断。Task_Voc 进循环前调一次。 */
bool uart_rx_start_voc(void);

/* 启动 USART2（上位机）的接收中断。Task_Host 进循环前调一次。 */
bool uart_rx_start_host(void);

#endif /* UART_RX_H */

#ifndef HOST_PROTO_H
#define HOST_PROTO_H

#include <stdint.h>
#include <stdbool.h>
#include "app_env.h"
#include "uart_rx.h"    /* UART_LINK_* —— 上位机链路的编号 */

/* ================================================================
 * 上位机通信协议
 *
 * 跑在**两条链路**上，同一套协议：
 *   UART_LINK_DEBUG —— USART2 + CH340   下位机调试用
 *   UART_LINK_BUS   —— USART6 + MAX3485 上位机 RS485 总线
 *
 * 每条链路各自的接收状态（行缓冲、诊断计数器）独立，互不干扰 ——
 * 共用一个缓冲的话，两条链路同时来的半截命令会拼在一起，
 * 表现为"偶尔有命令不生效"，而且完全随机、极难查。
 *
 * 选 ASCII 键值对 + 异或校验，理由：
 *   - 串口助手直接可读，调试不用对着十六进制数
 *   - Qt 端 split(',') + split('=') 就能解析，不用处理字节序和结构体
 *   - 和硬件台账里写的"115200 8N1，ASCII"一致
 *
 * 帧格式（每帧以 \r\n 结尾）：
 *
 *     $<类型>,<node>[,<key>=<value>]...*<两位大写十六进制校验><CR><LF>
 *
 *   校验和 = '$' 和 '*' 之间所有字符的逐字节异或
 *
 * ---- 上行（下位机 → 上位机），Task_Host 每 500ms 在两条链路各发一帧 ----
 *
 *   $ENV,1,T=26.4,H=62.0,CO2=420,VOC=123,HCHO=45,SMK=12,GAS=3,LUX=58,
 *        ALM=0,LINK=1,AUTO=0,MAN=0,RXB=0,RXL=0,RXO=0,
 *        SPT=30.0,SPH=70.0,SPC=1000,SPS=15,SPG=15,SPL=30*XX
 *
 *     T    温度 ℃            H     湿度 %RH
 *     CO2  eCO2 ppm          VOC   VOC ug/m3
 *     HCHO 甲醛 ug/m3        SMK   烟雾 0~100
 *     GAS  有毒气体 0~100     LUX   光照 0~100
 *     ALM  报警等级 0/1/2     LINK  21VOC 是否在线 0/1
 *     AUTO 自动通风 0/1       MAN   手动通风 0/1
 *
 *     RXB  该链路收到的字节总数   RXL  收满的行数   RXO  生效的命令数
 *          —— 下行链路诊断。**这三个数是"这条链路"的**（你从哪个口
 *          收到这帧，报的就是那个口的接收情况），上位机拿它们就能判断
 *          "我发的命令为什么没反应"：
 *
 *            RXB 一直不涨          → 字节根本没到 MCU（接线 / 助手没发出去）
 *            RXB 在涨、RXL 不涨     → 字节到了但凑不出整行：**行终止符没加
 *                                     或加错**（串口助手的"发送新行"）
 *            RXL 在涨、RXO 不涨     → 行收满了但校验不过（校验和算错）
 *            RXO 在涨              → 命令生效了，问题在下游
 *
 *     SPT / SPH / SPC / SPS / SPG / SPL
 *          = 设备**当前实际在用**的六个阈值（温度 / 湿度 / CO2 / 烟雾 /
 *            有毒气体 / 开灯）。上位机靠它们可以核对"我设的值生效了没"。
 *
 *            为什么要有这几个字段：**屏幕显示的值和固件里真正用的值不一定
 *            是同一个**。调这种"设置了但不生效"的问题时，必须看设备实际
 *            在用的那份配置，不能只看界面。
 *
 * ---- 下行（上位机 → 下位机），解析后写进 cfg ----
 *
 *   $SET,1,T=28,H=70,CO2=1000,SMK=15,GAS=15,LUX=30*XX    改阈值
 *   $FAN,1,AUTO=1,MAN=0*XX                                改通风开关
 *
 *   设计取舍：
 *   - 上位机**建议全量下发**阈值（幂等，不怕丢帧导致参数错乱），但解析器
 *     只更新"这帧里出现的字段"，没出现的保持原值 —— 这样调试时发单个
 *     字段也能生效。
 *   - 未知的 key 直接忽略，以后加字段不会破坏旧固件。
 *   - 数值一律钳到合法范围（见 app_env.h 的 CFG_*_MIN/MAX）。
 *   - **node 字段会被校验**：`0` 表示广播（任何节点都执行），其它值必须
 *     等于本机编号，否则整帧忽略。多节点组网时这一条是必须的 ——
 *     不然总线上的命令会被所有节点一起执行。
 *
 * 注意：本模块**完全不使用浮点**。这个工程的链接参数是
 * --specs=nano.specs 且没有 -u _printf_float，newlib-nano 默认不编浮点
 * 格式化，直接写 snprintf("%.1f") 会静默输出空字符串。所以温度湿度用
 * "放大 10 倍的整数"自己拼字符串，整数运算没有任何依赖。
 * （界面上的 %.1f 是 LVGL 自己的 printf，另一套，不受影响。）
 * ================================================================ */

/* 上行一帧的最大长度（含 '\0'）。
   最坏情况（负温度 + 所有计数器都吃到 10 位 4294967295）约 205 字符，
   取 256 留出余量。host_build_telemetry 会检查是否截断，不够会返回 0。 */
#define HOST_TX_BUF_LEN     256

/* 下行一行的最大长度（含 '\0'） */
#define HOST_RX_LINE_LEN    96

void host_proto_init(void);

/* 启动某条链路的接收中断 + 复位它的接收状态。Task_Host 进循环前对
   每条链路各调一次。lk 取 UART_LINK_*。 */
bool host_start(int lk);

/* 组一帧遥测，写进 buf（含结尾的 '\0'）。
 *
 * node —— 本机编号，会写进帧里
 * lk   —— 这帧准备从哪条链路发出去。用它选取该链路的 RXB/RXL/RXO，
 *         所以**同一个时刻两条链路组出来的帧内容是不同的**（各自的
 *         接收诊断不同）—— 这是有意的。
 *
 * 返回写入的字符数（不含 '\0'）；buf 不够大则返回 0。 */
int host_build_telemetry(char *buf, int buflen, uint8_t node, int lk,
                         const env_t *e, const cfg_t *c);

/* ISR 上下文：逐字节喂进某条链路的行缓冲（串口收到什么就喂什么）。
   收满一个 '\n' 结尾的整行时返回 true。 */
bool host_rx_byte(int lk, uint8_t b);

/* 任务上下文：取走某条链路最近收满的一行（已去掉行终止符，但保留
   *XX 校验段）。out 里会得到以 '\0' 结尾的字符串，超长会截断。
   没有新行可取时返回 false。
 *
 * 用"取走式"而不是"查询式"是有意的：查询式的话，刚收满的一行会在
 * **下一个字节到来的瞬间**失效，而这个任务 5ms 才轮询一次 ——
 * 上位机连着发两条命令时，第一条就会被第二条的开头冲掉。 */
bool host_take_line(int lk, char *out, int out_len);

/* ISR 上下文：清空某条链路的行缓冲，丢掉收到的半截行。
   串口出错（过载/帧错误）后由 uart_rx.c 调用。 */
void host_rx_reset(int lk);

/* 解析一帧下行命令。帧头、校验、node 都对才返回 true，
   并按命令更新 *c（数值会被钳到合法范围）。未知字段忽略。
 *
 * my_node —— 本机编号，用来校验帧里的 node（0 = 广播，任何节点都执行）。
 *            不匹配的帧直接返回 false，**什么都不会改**。 */
bool host_parse_cmd(const char *line, uint8_t my_node, cfg_t *c);

#endif /* HOST_PROTO_H */
